#!/usr/bin/env python3
"""Blind synthetic benchmark for semantic control-plane routing.

The cases exercise operator paraphrases rather than evaluation questions. The
expected numeric result is generated by compiling the declared typed operator
and executing it against DuckDB, keeping the model out of answer generation.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path


CURRENT_DIR = Path(__file__).resolve().parent
sys.path[:0] = [
    str(CURRENT_DIR),
    str(CURRENT_DIR / "agent"),
    str(CURRENT_DIR / "db"),
]

from agentic_controller import AgenticController
from intent_planner import IntentPlanner
from retriever import SubtaskRetriever


@dataclass(frozen=True)
class Case:
    question: str
    answer_type: str
    expected_operator: str


CASES = [
    Case(
        "For Suvarna Projects, report its portfolio less Water Treatment.",
        "money",
        "exclusion_aggregate",
    ),
    Case(
        "For Mahanadi Steel, add only tunnels plus irrigation work.",
        "money",
        "category_aggregate",
    ),
    Case(
        "Of Peninsular Petroleums invoices, what fraction out of 100 has been settled?",
        "percent",
        "collection_rate",
    ),
    Case(
        "Show the complete awarded-work position of the NSPO account.",
        "money",
        "hop_aggregate",
    ),
    Case(
        "Contrast Trishakti's biggest completed job with the runner-up.",
        "money",
        "rank_value",
    ),
    Case(
        "What invoice balance is yet unsettled for Suvarna Projects?",
        "money",
        "ar_outstanding",
    ),
    Case(
        "What share of Mahanadi Steel jobs carry endorsements?",
        "percent",
        "referenced_share",
    ),
]


def main() -> None:
    planner = IntentPlanner()
    retriever = SubtaskRetriever()
    controller = AgenticController(planner, retriever, enabled=True)
    if not controller.enabled:
        raise SystemExit("Agent controller is disabled; check .env and the local server")

    seeds = []
    for case in CASES:
        plan = planner.plan(case.question, case.answer_type)
        seeds.append((plan, retriever.execute_plan(plan)))

    baseline_correct = sum(
        seed_plan.pattern == case.expected_operator
        for case, (seed_plan, _seed_context) in zip(CASES, seeds)
    )
    stats = controller.prepare_batch(seeds)
    agent_correct = 0
    answer_correct = 0

    for index, (case, (seed_plan, seed_context)) in enumerate(zip(CASES, seeds), 1):
        expected_plan = controller._compile_decision(
            seed_plan,
            {
                "pattern": case.expected_operator,
                "confidence": 1.0,
                "slots": {},
            },
        )
        expected_context = retriever.execute_plan(expected_plan)
        outcome = controller.refine(seed_plan, seed_context)
        operator_ok = outcome.plan.pattern == case.expected_operator
        value_ok = outcome.context.candidate_answer == expected_context.candidate_answer
        agent_correct += operator_ok
        answer_correct += value_ok
        print(
            f"[{index}/{len(CASES)}] seed={seed_plan.pattern:22s} "
            f"agent={outcome.plan.pattern:22s} expected={case.expected_operator:22s} "
            f"operator_ok={operator_ok} answer_ok={value_ok} source={outcome.source}"
        )

    print(
        "SUMMARY "
        f"baseline_operators={baseline_correct}/{len(CASES)} "
        f"agent_operators={agent_correct}/{len(CASES)} "
        f"agent_answers={answer_correct}/{len(CASES)} "
        f"batches={stats['model_batches']} fallbacks={stats['fallbacks']}"
    )


if __name__ == "__main__":
    main()
